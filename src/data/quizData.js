export function getQuestionsByOrgan(organId, count = 5) {
  const questionsList = QUIZ_ORGAN_BANK[organId] || [];
  
  if (questionsList.length > 0) {
    const shuffled = [...questionsList].sort(() => 0.5 - Math.random());
    return shuffled.slice(0, count);
  }  
  return getRandomQuestions(count);
}

export function getRandomQuestions(count = 5) {
  const allQuestions = Object.values(QUIZ_ORGAN_BANK).flat();
  const shuffled = allQuestions.sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}

